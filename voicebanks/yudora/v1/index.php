		<br>
		<h3>How to use:</h3>
		To use this bank, simply select the voice you would like to use in UTAU! If you want to
		use any of the "all_" banks (which are packages of all of the appends for that language),
		then you have to add suffixes for each append. The suffixes are as follows: <br><br>
			<li>no suffix: -starcore- (Core, Natural Voicebank)</li>
			<li> S: -supernova- (Strong, Powerful Voicebank)</li>
			<li> N: -nebula- (Soft, Whispery Voicebank)</li>
