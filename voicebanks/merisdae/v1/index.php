<div class="row">
	<div class="column flex50 centervertical">
		<center>
			<img src="logo.png" width="100%"><br><br>
			Thank you for your interest in Merisdae's Classic v1 Voicebanks!<br><br>
			Merisdae has 5 different banks, each named after a phase of the moon.
			Each bank has multiple languages in it, in multiple pitches!
			The pitches are G3, C4, G4, B4, and D5.<br><br>
			For instructions on how to use Merisdae v1 voicebanks, please see below!
		</center><br>
		<h3>How to use:</h3>
		To use this bank, simply select the voice you would like to use in UTAU! If you want to
		use any of the "all_" banks (which are packages of all of the appends for that language),
		then you have to add suffixes for each append. The suffixes are as follows:
		<ol>
			<li>no suffix: -crescentmoon- (Core, Natural Voicebank)</li>
			<li>_p: -bloodmoon- (Strong, Powerful Voicebank)</li>
			<li>_s: -bluemoon- (Soft, Whispery Voicebank)</li>
			<li>_f: -fullmoon- (Deeper, Mature Voicebank)</li>
			<li>_n: -newmoon- (Cute, Childish Voicebank)</li>
		</ol>
